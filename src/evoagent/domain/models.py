"""
Pydantic domain models for tasks, execution budgets, patches, and evaluation records.
"""

from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field
from evoagent.domain.states import TaskState


class ExecutionBudget(BaseModel):
    """Resource constraints for an autonomous repair task."""

    max_attempts: int = Field(default=3, ge=1, le=10)
    max_tool_calls: int = Field(default=10, ge=1, le=50)
    max_patch_lines: int = Field(default=150, ge=10, le=1000)
    timeout_seconds: int = Field(default=60, ge=5, le=600)


class Task(BaseModel):
    """Specification of a bug repair task."""

    task_id: str
    repository_path: Path
    issue_description: str
    failure_signature: Optional[str] = None
    targeted_test: str = Field(
        ...,
        description="Path or test node to verify reproduction and fix",
    )
    regression_test: Optional[str] = Field(
        default=None,
        description="Path or test node for regression suite",
    )
    budget: ExecutionBudget = Field(default_factory=ExecutionBudget)
    metadata: Dict[str, Any] = Field(default_factory=dict)
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


class PatchProposal(BaseModel):
    """Proposed unified diff repair generated by the model or heuristic."""

    target_file: str
    diff_unified: str
    rationale: str = ""
    lines_added: int = 0
    lines_removed: int = 0
    is_valid_format: bool = True
    validation_error: Optional[str] = None


class TestResult(BaseModel):
    """Execution output and metrics from running a test suite."""

    __test__ = False

    command: str
    passed: bool
    exit_code: int
    stdout: str
    stderr: str
    duration_seconds: float
    error_summary: Optional[str] = None


class EvaluationScore(BaseModel):
    """Independent evaluation of a patch attempt."""

    targeted_tests_passed: bool
    regression_tests_passed: bool
    patch_syntactically_valid: bool
    is_accepted: bool
    score: float = Field(default=0.0, ge=0.0, le=1.0)
    feedback: str = ""


class AttemptRecord(BaseModel):
    """Trace of a single repair cycle."""

    attempt_number: int
    state: TaskState
    hypothesis: Optional[str] = None
    patch: Optional[PatchProposal] = None
    pre_test_result: Optional[TestResult] = None
    post_test_result: Optional[TestResult] = None
    evaluation: Optional[EvaluationScore] = None
    tool_calls_count: int = 0
    timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


class TaskResult(BaseModel):
    """Final auditable record of an EvoAgent task run."""

    task_id: str
    final_state: TaskState
    is_successful: bool
    attempts: List[AttemptRecord] = Field(default_factory=list)
    accepted_patch: Optional[PatchProposal] = None
    total_duration_seconds: float = 0.0
    completed_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


class MemoryEpisode(BaseModel):
    """Episodic memory record for future retrieval and dataset curation."""

    episode_id: str
    task_id: str
    issue_description: str
    failure_signature: str
    target_file: str
    root_cause_hypothesis: str
    applied_patch: str
    outcome: str = Field(..., description="'accepted' or 'rejected'")
    targeted_tests_passed: bool
    regression_tests_passed: bool
    lessons_learned: str
    strategy_id: str = "default"
    model_version: str = "baseline"
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    metadata: Dict[str, Any] = Field(default_factory=dict)


# Alias for backward compatibility across modules
MemoryEpisodeRecord = MemoryEpisode
